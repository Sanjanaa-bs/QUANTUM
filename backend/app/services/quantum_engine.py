def _build_hadamard_circuit(num_qubits: int = 1) -> "QuantumCircuit":
    """
    Build an n-qubit Hadamard measurement circuit.

    Circuit:
        q[0..n-1] initialized to |0⟩
        H gate applied to each qubit → state becomes ((|0⟩ + |1⟩)/√2)^⊗n
        Measurement of all qubits → classical register c[0..n-1]

    Returns the QuantumCircuit object.
    """
    if not QISKIT_AVAILABLE:
        raise RuntimeError("Qiskit is not installed.")
    num_qubits = max(1, min(8, int(num_qubits)))
    qc = QuantumCircuit(num_qubits, num_qubits, name=f"QRNG_Hadamard_{num_qubits}q")
    for i in range(num_qubits):
        qc.h(i)
        qc.measure(i, i)
    return qc


def _counts_to_bitstream(counts: Dict[str, int], target_bits: Optional[int] = None) -> str:
    """
    Reconstruct a bitstream from aggregated measurement counts.

    IMPORTANT: Aggregated counts do NOT preserve chronological shot order.
    The bits are reconstructed in ascending key order for determinism.
    In Qiskit, measurement keys represent classical registers in little-endian notation,
    where the rightmost character is c[0] and the leftmost is c[n-1].
    Reversing the multi-bit key yields standard qubit index order c[0], c[1], ..., c[n-1].

    Args:
        counts: e.g. {"0": 5012, "1": 4988} for 1 qubit, or {"00": 250, "01": 250, ...}
        target_bits: Optional target bit count to truncate to.

    Returns:
        A string of 0s and 1s, sorted by key for determinism.
    """
    parts: List[str] = []
    for key in sorted(counts.keys()):
        clean_key = key.strip()
        if len(clean_key) == 1:
            parts.append(clean_key * counts[key])
        else:
            ordered_shot = clean_key[::-1]
            parts.append(ordered_shot * counts[key])
    result = "".join(parts)
    if target_bits is not None and len(result) > target_bits:
        result = result[:target_bits]
    return result


def _compute_stats(bitstream: str) -> Dict[str, Any]:
    """Compute descriptive statistics for a binary string."""
    n = len(bitstream)
    if n == 0:
        return {
            "total_bits": 0, "zeros": 0, "ones": 0,
            "proportion_ones": 0.0, "proportion_zeros": 0.0,
            "bias_deviation": 0.5, "shannon_entropy_per_bit": 0.0,
            "min_entropy_per_bit": 0.0,
        }
    ones = bitstream.count("1")
    zeros = n - ones
    p1 = ones / n
    p0 = zeros / n
    # Shannon entropy H(X) = -p0*log2(p0) - p1*log2(p1)
    def _h(p: float) -> float:
        return 0.0 if p <= 0.0 else -p * math.log2(p)
    entropy = _h(p0) + _h(p1)
    max_p = max(p0, p1)
    min_entropy = 0.0 if (max_p <= 0.0 or max_p >= 1.0) else -math.log2(max_p)
    return {
        "total_bits": n,
        "zeros": zeros,
        "ones": ones,
        "proportion_ones": round(p1, 6),
        "proportion_zeros": round(p0, 6),
        "bias_deviation": round(abs(p1 - 0.5), 6),
        "shannon_entropy_per_bit": round(entropy, 6),
        "min_entropy_per_bit": round(min_entropy, 6),
    }


def _build_readout_noise_model(
    prob_meas0_prep1: float = 0.05,
    prob_meas1_prep0: float = 0.05,
) -> "NoiseModel":
    """
    Build a simple single-qubit readout-error noise model.

    Parameters:
        prob_meas0_prep1: P(measure 0 | qubit prepared in |1⟩)
        prob_meas1_prep0: P(measure 1 | qubit prepared in |0⟩)

    Note: This simplified model does not reproduce any real quantum device.
    Actual device noise includes gate errors, decoherence, and crosstalk.
    """
    if not QISKIT_AVAILABLE:
        raise RuntimeError("Qiskit is not installed.")
    noise_model = NoiseModel()
    # ReadoutError([[P(0|0), P(1|0)], [P(0|1), P(1|1)]])
    ro_error = ReadoutError([
        [1 - prob_meas1_prep0, prob_meas1_prep0],  # prepared |0⟩
        [prob_meas0_prep1, 1 - prob_meas0_prep1],  # prepared |1⟩
    ])
    noise_model.add_all_qubit_readout_error(ro_error)
    return noise_model


def run_ideal_simulation(
    num_bits: int,
    num_qubits: int = 1,
    seed: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Run an ideal (noiseless) Hadamard-gate simulation.

    Supports configurable qubit count (1, 2, 4, 8) in parallel Hadamard register.
    Returns a result dictionary with bitstream, counts, stats, and metadata.
    """
    if not QISKIT_AVAILABLE:
        raise RuntimeError("Qiskit / Qiskit-Aer is not installed.")

    experiment_id = str(uuid.uuid4())
    warnings: List[str] = []

    num_qubits = max(1, min(8, int(num_qubits)))
    shots = math.ceil(num_bits / num_qubits)

    qc = _build_hadamard_circuit(num_qubits=num_qubits)
    circuit_description = (
        f"Hadamard register on {num_qubits} qubit(s): |0⟩^⊗{num_qubits} → H^⊗{num_qubits} → Measure. "
        f"Shots executed: {shots}. Yielding up to {shots * num_qubits} bits (truncated to {num_bits})."
    )

    simulator = AerSimulator()
    simulator_options: Dict[str, Any] = {"shots": shots, "memory": True}
    if seed is not None:
        simulator_options["seed_simulator"] = seed
    else:
        simulator_options["seed_simulator"] = secrets.randbits(31)

    t0 = time.perf_counter()
    job = simulator.run(qc, **simulator_options)
    result = job.result()
    elapsed = time.perf_counter() - t0

    counts = result.get_counts()
    normalized: Dict[str, int] = {}
    for k, v in counts.items():
        normalized[k.strip()] = v

    try:
        raw_memory = result.get_memory()
        if num_qubits == 1:
            bitstream = "".join(raw_memory)[:num_bits]
        else:
            ordered_shots = [s.strip()[::-1] for s in raw_memory]
            bitstream = "".join(ordered_shots)[:num_bits]
    except Exception:
        bitstream = _counts_to_bitstream(normalized, target_bits=num_bits)
        warnings.append(
            "Aggregated counts fallback used. Shot chronological order could not be retrieved."
        )
    stats = _compute_stats(bitstream)

    if seed is not None:
        warnings.append(
            "Seeded simulation: reproducible but NOT random in the cryptographic sense."
        )
    if num_qubits > 1:
        warnings.append(
            f"Multi-qubit mode ({num_qubits} qubits): simulated via joint statevector pseudo-random sampling. "
            "Does not automatically guarantee physical independence."
        )

    return {
        "experiment_id": experiment_id,
        "source_type": "ideal_simulator",
        "backend_name": f"AerSimulator (ideal, {num_qubits}q)",
        "num_qubits": num_qubits,
        "shots_executed": shots,
        "requested_bits": num_bits,
        "actual_bits": len(bitstream),
        "bitstream": bitstream,
        "measurement_counts": normalized,
        "circuit_description": circuit_description,
        "noise_params": None,
        "seed_used": seed,
        "is_seeded": seed is not None,
        "execution_time_seconds": round(elapsed, 4),
        "stats": stats,
        "warnings": warnings,
        "source_classification_note": SOURCE_NOTES["ideal_simulator"],
    }


def run_noisy_simulation(
    num_bits: int,
    num_qubits: int = 1,
    prob_meas0_prep1: float = 0.05,
    prob_meas1_prep0: float = 0.05,
    seed: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Run a noisy Hadamard-gate simulation with a readout-error model.

    Noise parameters are documented in experiment metadata.
    This does NOT reproduce any specific real quantum device.
    """
    if not QISKIT_AVAILABLE:
        raise RuntimeError("Qiskit / Qiskit-Aer is not installed.")

    experiment_id = str(uuid.uuid4())
    warnings: List[str] = []

    num_qubits = max(1, min(8, int(num_qubits)))
    shots = math.ceil(num_bits / num_qubits)

    noise_params = {
        "model": "readout_error",
        "prob_meas0_prep1": prob_meas0_prep1,
        "prob_meas1_prep0": prob_meas1_prep0,
        "num_qubits": num_qubits,
        "note": (
            "Simplified readout-error model applied to all qubits. Does not reproduce any "
            "specific real quantum device."
        ),
    }

    qc = _build_hadamard_circuit(num_qubits=num_qubits)
    noise_model = _build_readout_noise_model(prob_meas0_prep1, prob_meas1_prep0)

    circuit_description = (
        f"{num_qubits}-qubit register: |0⟩^⊗{num_qubits} → H^⊗{num_qubits} → Measure (readout noise: "
        f"P(0|1)={prob_meas0_prep1}, P(1|0)={prob_meas1_prep0}). Shots: {shots}."
    )

    simulator = AerSimulator(noise_model=noise_model)
    simulator_options: Dict[str, Any] = {"shots": shots, "memory": True}
    if seed is not None:
        simulator_options["seed_simulator"] = seed
    else:
        simulator_options["seed_simulator"] = secrets.randbits(31)

    t0 = time.perf_counter()
    job = simulator.run(qc, **simulator_options)
    result = job.result()
    elapsed = time.perf_counter() - t0

    counts = result.get_counts()
    normalized: Dict[str, int] = {}
    for k, v in counts.items():
        normalized[k.strip()] = v

    try:
        raw_memory = result.get_memory()
        if num_qubits == 1:
            bitstream = "".join(raw_memory)[:num_bits]
        else:
            ordered_shots = [s.strip()[::-1] for s in raw_memory]
            bitstream = "".join(ordered_shots)[:num_bits]
    except Exception:
        bitstream = _counts_to_bitstream(normalized, target_bits=num_bits)
        warnings.append(
            "Aggregated counts fallback used. Shot chronological order could not be retrieved."
        )
    stats = _compute_stats(bitstream)

    warnings.append(
        "SIMULATION (Noisy): Readout-error model introduces asymmetry. "
        "This is NOT physical quantum hardware."
    )
    if num_qubits > 1:
        warnings.append(
            f"Multi-qubit mode ({num_qubits} qubits): simulated with readout error on each qubit."
        )
    if seed is not None:
        warnings.append("Seeded noisy simulation: reproducible.")

    return {
        "experiment_id": experiment_id,
        "source_type": "noisy_simulator",
        "backend_name": f"AerSimulator ({num_qubits}q readout noise p01={prob_meas0_prep1}, p10={prob_meas1_prep0})",
        "num_qubits": num_qubits,
        "shots_executed": shots,
        "requested_bits": num_bits,
        "actual_bits": len(bitstream),
        "bitstream": bitstream,
        "measurement_counts": normalized,
        "circuit_description": circuit_description,
        "noise_params": noise_params,
        "seed_used": seed,
        "is_seeded": seed is not None,
        "execution_time_seconds": round(elapsed, 4),
        "stats": stats,
        "warnings": warnings,
        "source_classification_note": SOURCE_NOTES["noisy_simulator"],
    }


def get_circuit_diagram_text(num_qubits: int = 1) -> str:
    """Return an ASCII representation of the QRNG circuit."""
    if not QISKIT_AVAILABLE:
        return "Qiskit not available."
    qc = _build_hadamard_circuit(num_qubits=num_qubits)
    return qc.draw(output="text").single_string()


