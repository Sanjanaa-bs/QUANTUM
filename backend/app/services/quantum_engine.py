"""
Quantum Engine Service
======================
Generates random bits using Qiskit quantum circuit simulation.

Scientific Notes:
- A qubit initialized in |0⟩ and measured after a Hadamard gate has
  ideal measurement probabilities P(0) = P(1) = 0.5.
- Simulator runs use classical computation and pseudo-random sampling.
  They are NOT a source of physical quantum randomness or physical entropy.
- Seeded simulation is reproducible but NOT random in the cryptographic sense.
- Aggregated measurement counts cannot recover the temporal ordering of shots.

Supported modes:
  A. Ideal quantum circuit simulation (Qiskit Aer statevector/qasm simulator)
  B. Noisy simulation with a configurable readout-error model
  C. Real IBM Quantum hardware (optional — requires IBM_QUANTUM_TOKEN env var)
"""

