def compute_shannon_entropy(p0: float, p1: float) -> float:
    """
    Compute Shannon entropy per bit for binary probabilities.
    Handles p0=0 or p1=0 safely by convention 0*log2(0) = 0.
    """
    if p0 <= 0.0 or p1 <= 0.0:
        return 0.0
    h = 0.0
    if p0 > 0.0:
        h -= p0 * math.log2(p0)
    if p1 > 0.0:
        h -= p1 * math.log2(p1)
    return round(h, 6)


def compute_min_entropy(p0: float, p1: float) -> float:
    """
    Compute empirical min-entropy estimate for binary probabilities:
    H_min = -log2(max(p0, p1))

    Returns 0.0 if either probability is 1.0 or if inputs are empty/invalid.
    Returns 1.0 if p0 == p1 == 0.5.
    """
    max_p = max(p0, p1)
    if max_p <= 0.0 or max_p >= 1.0:
        return 0.0
    return round(-math.log2(max_p), 6)


def compute_entropy_profile(bitstream: str) -> Dict[str, Any]:
    """
    Compute full entropy profile for a binary string.
    Handles empty bitstreams safely.
    """
    n = len(bitstream)
    if n == 0:
        return {
            "total_bits": 0,
            "zeros": 0,
            "ones": 0,
            "proportion_zeros": 0.0,
            "proportion_ones": 0.0,
            "bias_deviation": 0.5,
            "shannon_entropy_per_bit": 0.0,
            "min_entropy_per_bit": 0.0,
        }

    ones = bitstream.count("1")
    zeros = n - ones
    p1 = ones / n
    p0 = zeros / n

    shannon = compute_shannon_entropy(p0, p1)
    min_ent = compute_min_entropy(p0, p1)
    bias = round(abs(p1 - 0.5), 6)

    return {
        "total_bits": n,
        "zeros": zeros,
        "ones": ones,
        "proportion_zeros": round(p0, 6),
        "proportion_ones": round(p1, 6),
        "bias_deviation": bias,
        "shannon_entropy_per_bit": shannon,
        "min_entropy_per_bit": min_ent,
    }


def window_entropy_analysis(
    bitstream: str,
    window_size: int = 256,
    step_size: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Perform window-based entropy analysis across a binary bitstream.

    Args:
        bitstream: Binary string of '0's and '1's.
        window_size: Length of each window in bits (minimum 16).
        step_size: Step size for sliding window. If None, defaults to window_size (non-overlapping).

    Returns:
        Dictionary containing:
          - window_size, step_size, num_windows
          - windows: list of dicts with window_index, start_bit, end_bit, p0, p1, shannon_entropy, min_entropy
          - summary: mean, min, max, std_dev for Shannon and min-entropy
    """
    n = len(bitstream)
    if window_size < 16:
        window_size = 16
    if step_size is None or step_size < 1:
        step_size = window_size

    if n < window_size:
        # Not enough bits for even one window
        overall = compute_entropy_profile(bitstream)
        return {
            "window_size": window_size,
            "step_size": step_size,
            "num_windows": 0,
            "windows": [],
            "summary": {
                "mean_shannon": overall["shannon_entropy_per_bit"],
                "min_shannon": overall["shannon_entropy_per_bit"],
                "max_shannon": overall["shannon_entropy_per_bit"],
                "std_shannon": 0.0,
                "mean_min_entropy": overall["min_entropy_per_bit"],
                "min_min_entropy": overall["min_entropy_per_bit"],
                "max_min_entropy": overall["min_entropy_per_bit"],
                "std_min_entropy": 0.0,
            },
            "warning": f"Bitstream length ({n}) is smaller than window size ({window_size}).",
        }

    windows: List[Dict[str, Any]] = []
    shannon_values: List[float] = []
    min_entropy_values: List[float] = []

    window_idx = 0
    start = 0
    while start + window_size <= n:
        end = start + window_size
        chunk = bitstream[start:end]
        c_ones = chunk.count("1")
        c_zeros = window_size - c_ones
        p1 = c_ones / window_size
        p0 = c_zeros / window_size
        h_shannon = compute_shannon_entropy(p0, p1)
        h_min = compute_min_entropy(p0, p1)

        shannon_values.append(h_shannon)
        min_entropy_values.append(h_min)

        windows.append({
            "window_index": window_idx,
            "start_bit": start,
            "end_bit": end,
            "proportion_ones": round(p1, 4),
            "proportion_zeros": round(p0, 4),
            "bias_deviation": round(abs(p1 - 0.5), 4),
            "shannon_entropy": h_shannon,
            "min_entropy": h_min,
        })

        window_idx += 1
        start += step_size

    # Summary statistics
    def _mean(vals: List[float]) -> float:
        return round(sum(vals) / len(vals), 6) if vals else 0.0

    def _std(vals: List[float], mean_val: float) -> float:
        if len(vals) <= 1:
            return 0.0
        var = sum((v - mean_val) ** 2 for v in vals) / len(vals)
        return round(math.sqrt(var), 6)

    mean_sh = _mean(shannon_values)
    mean_min = _mean(min_entropy_values)

    return {
        "window_size": window_size,
        "step_size": step_size,
        "num_windows": len(windows),
        "windows": windows,
        "summary": {
            "mean_shannon": mean_sh,
            "min_shannon": min(shannon_values) if shannon_values else 0.0,
            "max_shannon": max(shannon_values) if shannon_values else 0.0,
            "std_shannon": _std(shannon_values, mean_sh),
            "mean_min_entropy": mean_min,
            "min_min_entropy": min(min_entropy_values) if min_entropy_values else 0.0,
            "max_min_entropy": max(min_entropy_values) if min_entropy_values else 0.0,
            "std_min_entropy": _std(min_entropy_values, mean_min),
        },
        "explanations": ENTROPY_EXPLANATIONS,
    }


def compare_entropy_profiles(raw_bits: str, debiased_bits: str) -> Dict[str, Any]:
    """
    Compare information-theoretic metrics between raw and debiased streams.
    """
    raw_profile = compute_entropy_profile(raw_bits)
    deb_profile = compute_entropy_profile(debiased_bits)

    shannon_gain = round(deb_profile["shannon_entropy_per_bit"] - raw_profile["shannon_entropy_per_bit"], 6)
    min_entropy_gain = round(deb_profile["min_entropy_per_bit"] - raw_profile["min_entropy_per_bit"], 6)
    bias_reduction = round(raw_profile["bias_deviation"] - deb_profile["bias_deviation"], 6)

    return {
        "raw": raw_profile,
        "debiased": deb_profile,
        "shannon_entropy_gain": shannon_gain,
        "min_entropy_gain": min_entropy_gain,
        "bias_reduction": bias_reduction,
        "explanations": ENTROPY_EXPLANATIONS,
    }


def calculate_sliding_window_proportions(
    bitstream: str,
    window_size: int,
    step_size: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Calculate sliding-window proportion of 1s across a chronological binary sequence.

    Formula:
        proportion_ones = count('1') / W

    Args:
        bitstream: Chronological binary string of '0' and '1'.
        window_size: Size of sliding window W (1 <= W <= len(bitstream)).
        step_size: Step size for window progression (default: max(1, window_size // 2)).

    Returns:
        Dictionary with positions, ones_counts, proportions, and summary metrics.

    Raises:
        ValueError: If input contains invalid characters, is empty, or window_size is invalid.
    """
    if not isinstance(bitstream, str):
        raise ValueError("Bitstream must be a string.")

    n = len(bitstream)
    if n == 0:
        raise ValueError("Bitstream cannot be empty.")

    for ch in bitstream:
        if ch not in ("0", "1"):
            raise ValueError(f"Invalid non-binary character {ch!r} in bitstream.")

    if not isinstance(window_size, int) or window_size < 1:
        raise ValueError("Window size must be a positive integer.")

    if window_size > n:
        raise ValueError(f"Window size ({window_size}) cannot exceed bitstream length ({n}).")

    if step_size is None or step_size < 1:
        step_size = max(1, window_size // 2)

    positions: List[int] = []
    ones_counts: List[int] = []
    proportions: List[float] = []

    for pos in range(0, n - window_size + 1, step_size):
        chunk = bitstream[pos : pos + window_size]
        c1 = chunk.count("1")
        positions.append(pos)
        ones_counts.append(c1)
        proportions.append(round(c1 / window_size, 6))

    if positions and (positions[-1] + window_size < n):
        last_pos = n - window_size
        if last_pos != positions[-1]:
            chunk = bitstream[last_pos : last_pos + window_size]
            c1 = chunk.count("1")
            positions.append(last_pos)
            ones_counts.append(c1)
            proportions.append(round(c1 / window_size, 6))

    return {
        "valid": True,
        "window_size": window_size,
        "step_size": step_size,
        "total_bits": n,
        "total_windows": len(positions),
        "positions": positions,
        "ones_counts": ones_counts,
        "proportions": proportions,
        "mean_proportion": round(sum(proportions) / len(proportions), 6) if proportions else 0.0,
    }


