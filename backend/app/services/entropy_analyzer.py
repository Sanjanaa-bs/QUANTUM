"""
Quantum Entropy Quality Analyzer
================================
Provides information-theoretic entropy calculations and window-based
stationarity analysis for binary bitstreams.

Metrics:
  - Shannon entropy per bit: H(X) = -p0*log2(p0) - p1*log2(p1)
    Measures the average information content or uncertainty per bit.
    Maximum is 1.0 bit/bit for a uniform distribution (p0 = p1 = 0.5).
  - Empirical min-entropy: H_min = -log2(max(p0, p1))
    Measures worst-case unpredictability; fundamental bound for randomness
    extraction (e.g. Leftover Hash Lemma).
    Maximum is 1.0 bit/bit when p0 = p1 = 0.5; minimum is 0.0 when completely biased.
  - Zero and one proportions: p0 = N0/N, p1 = N1/N.
  - Bias deviation: |p1 - 0.5|.
  - Window-based entropy analysis:
    Slides a window across the bitstream to detect non-stationarity, local drift,
    or localized clustering across the measurement sequence.
  - Raw versus debiased comparison.

Scientific Integrity Notice:
  Empirical entropy estimates reflect the statistical properties of the observed sample.
  They do NOT constitute certified physical entropy lower bounds (which require device-
  independent Bell tests or source-calibrated quantum optics models).
  Furthermore, classical simulator output contains NO physical entropy.
  Passing statistical checks does NOT guarantee cryptographic security.
"""

